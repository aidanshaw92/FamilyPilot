import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { mockVenues } from '@/src/data/mock-data';
import { meetHalfway } from '@/src/services/planning/meet-halfway';
import { PlanningFamily } from '@/src/services/planning/planner';
import { personaliseVenues } from '@/src/utils/personalise-venues';
import { FamilyMember, FamilyProfile, Venue } from '@/src/types';
import { MatchableVenueFacts } from '@/src/types/day-request';

/**
 * RANKING IS PINNED. These record the ORDER Home and Explore list places in (personaliseVenues) and the order and scores Meet
 * halfway offers, for several households. `golden/ranking-b7a9f28.json` was generated by running this file on the #194
 * release; `golden/ranking-after-grading.json` is the same after the category-aware grading (docs/FAMILY_FIT_GRADING.md),
 * whose one ranking change is the age factor: a confirmed playground (84), a reviewed provision (88) or the kind of place (80)
 * now count where only the neutral 75 did. The second test proves that is the only direction anything moved.
 */
const child = (id: string, name: string, age: number, extra: Partial<FamilyMember> = {}): FamilyMember => ({
  id, name, role: 'child', dateOfBirth: '', age, dobKnown: true, ageMonths: age === 0 ? 7 : null, mobility: ['walks'], ...extra,
});
const parent: FamilyMember = { id: 'p', name: 'Aidan', role: 'parent', dateOfBirth: '', age: 38 };
const household = (kids: FamilyMember[], must: FamilyProfile['mustHaveFacilities'] = []): FamilyProfile =>
  ({ id: 'f', parentName: 'Aidan', members: [parent, ...kids], homeLocation: 'Camden, London', homeLatitude: 51.539, homeLongitude: -0.142, budgetTier: 'moderate', maxDriveMinutes: 60, mustHaveFacilities: must, routines: [], memberships: [], travelCot: null }) as unknown as FamilyProfile;

const baseFacts = (id: string, over: Partial<MatchableVenueFacts> = {}): MatchableVenueFacts => ({
  placeId: id, name: id, category: 'museum', driveMinutes: 20, enrichmentStatus: 'enriched', minRecommendedAge: null, maxRecommendedAge: null,
  venueAgePolicy: null, toilets: 'yes', babyChanging: 'yes', parking: 'yes', pushchairSuitability: 'good', environment: 'indoor', energyLevel: 'moderate',
  visitDurationMinutes: null, estimatedSpend: null, goodToKnow: [], warnings: [], openingStatus: 'open', ...over,
}) as MatchableVenueFacts;
const hours = { timezone: 'Europe/London', periods: [0, 1, 2, 3, 4, 5, 6].map((d) => ({ open: { day: d, hour: 10, minute: 0 }, close: { day: d, hour: 17, minute: 0 } })) };
const mk = (id: string, lat: number, lng: number, drive: number, score: number, facts: Partial<MatchableVenueFacts>, category = 'museum'): Venue =>
  ({ id, name: id, category, latitude: lat, longitude: lng, driveMinutes: drive, imageUrl: '', familyScore: { score, factors: {} as never, explanation: [] }, enrichmentStatus: 'enriched',
    structuredOpeningHours: hours, trustedFacts: baseFacts(id, { category: category as never, ...facts }), facilities: [] }) as unknown as Venue;

const SYNTHETIC: Venue[] = [
  mk('practical-only-museum', 51.598, -0.238, 22, 82, { cafe: 'yes', playground: 'yes' }),
  mk('confirmed-ages-park', 51.56, -0.12, 14, 80, { category: 'park' as never, minRecommendedAge: 0, maxRecommendedAge: 10, environment: 'outdoor' }, 'park'),
  mk('older-kids-only', 51.52, -0.16, 18, 80, { minRecommendedAge: 7, maxRecommendedAge: 14 }),
  mk('unknown-everything', 51.57, -0.2, 25, 60, { toilets: 'unknown', babyChanging: 'unknown', parking: 'unknown', pushchairSuitability: 'unknown', enrichmentStatus: 'provider_only' as never }),
  mk('practical-only-farm', 51.62, -0.1, 30, 78, { cafe: 'yes' }, 'farm'),
];
const PROFILES: [string, FamilyProfile][] = [
  ['4yo+baby', household([child('c1', 'Sloane', 4), child('c2', 'Ozzie', 0, { mobility: ['buggy'] })])],
  ['6yo+2yo', household([child('c1', 'Sloane', 6), child('c2', 'Ozzie', 2)])],
  ['one 3yo', household([child('c1', 'Sloane', 3)], ['baby_changing'])],
  ['baby only', household([child('c1', 'Ozzie', 0, { mobility: ['carrier'] })])],
  ['three kids', household([child('c1', 'A', 9), child('c2', 'B', 5), child('c3', 'C', 1)])],
];
const venues = [...SYNTHETIC, ...mockVenues];

const fp = (): Record<string, unknown> => {
  const out: Record<string, unknown> = {};
  for (const [label, profile] of PROFILES) {
    out[`order:${label}`] = personaliseVenues(venues, profile).map((v) => `${v.id}:${v.familyScore.score}`);
  }
  const mine = { id: 'mine', label: 'Our family', area: 'NW1', latitude: 51.539, longitude: -0.142, ages: [4, 0], maxDriveMinutes: 60, pushchair: true, required: [], routines: [] } as PlanningFamily;
  const other = { id: 'connected-1', label: 'Hannah’s family', area: 'SE13', latitude: 51.46, longitude: -0.01, ages: [3], maxDriveMinutes: 60, pushchair: false, required: [], routines: [] } as PlanningFamily;
  for (const [label, profile] of PROFILES.slice(0, 3)) {
    const personalised = personaliseVenues(venues, profile);
    const result = meetHalfway({ venues: personalised, mine, other, date: '2026-10-17', arriveAt: '10:00', today: '2026-10-14', nowMinutes: 8 * 60 });
    out[`halfway:${label}`] = result.options.map((o) => `${o.venue.id}:${Math.round(o.score * 100) / 100}`);
  }
  return out;
};

describe('ranking', () => {
  const after = join(__dirname, 'golden', 'ranking-after-grading.json');
  const before = join(__dirname, 'golden', 'ranking-b7a9f28.json');

  it('Home/Explore order and Meet halfway order and scores match the golden for the category-aware grading', () => {
    const now = fp();
    if (process.env.GOLDEN_WRITE === '1') {
      writeFileSync(after, `${JSON.stringify(now, null, 2)}\n`);
      return;
    }
    expect(existsSync(after)).toBe(true);
    expect(now).toEqual(JSON.parse(readFileSync(after, 'utf8')));
  });

  it('against the #194 release (b7a9f28): the only ranking change is the age factor reading a confirmed playground, a reviewed provision or the kind of place, so no venue scores lower and the moves are listed in docs/FAMILY_FIT_GRADING.md', () => {
    const old = JSON.parse(readFileSync(before, 'utf8')) as Record<string, string[]>;
    const now = fp() as Record<string, string[]>;
    const parse = (entries: string[]) => Object.fromEntries(entries.map((e) => { const i = e.lastIndexOf(':'); return [e.slice(0, i), Number(e.slice(i + 1))]; }));
    for (const key of Object.keys(old).filter((k) => k.startsWith('order:'))) {
      const was = parse(old[key]);
      const is = parse(now[key]);
      expect(Object.keys(is).sort()).toEqual(Object.keys(was).sort());
      for (const id of Object.keys(was)) expect(is[id], `${key} ${id}`).toBeGreaterThanOrEqual(was[id]);
    }
  });
});
