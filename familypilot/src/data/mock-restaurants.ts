function features(partial: Partial<RestaurantFeatures> & Pick<RestaurantFeatures, 'kidsMenu' | 'highChairs' | 'babyChanging' | 'pushchairSpace' | 'stepFreeAccess' | 'accessibleToilet' | 'outdoorSeating' | 'playArea' | 'activityPacks' | 'parking'>): RestaurantFeatures {
  return {
    noiseLevel: 'moderate',
    bookingRecommended: false,
    serviceSpeed: 'relaxed',
    dietaryOptions: [],
    ...partial,
  };
}

function baseScore(score: number, explanation: string[]): FamilyScore {
  return {
    score,
    factors: {
      ageSuitability: score - 2,
      accessibility: score - 4,
      distance: score,
      weatherFit: 85,
      budgetFit: score - 3,
      facilitiesMatch: score - 1,
      popularity: 78,
    },
    explanation,
  };
}

