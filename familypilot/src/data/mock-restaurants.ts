export function getDriveMinutesFromActivity(restaurantId: string, activityVenueId: string): number | null {
  return RESTAURANT_PROXIMITY[restaurantId]?.[activityVenueId] ?? null;
}

export function isActivityVenue(detail: VenueDetail): boolean {
  return detail.category !== 'restaurant' && detail.category !== 'cafe';
}
