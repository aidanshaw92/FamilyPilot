/**
 * Builds src/data/london-basemap.ts: the background Meet halfway draws its map on.
 *
 * WHY A BUNDLED MAP. A tiled map means a map provider: an account and a bill (Google, Mapbox, MapTiler), or a free public
 * server whose policy forbids apps (OpenStreetMap's own tiles), and in every case a third party that sees each viewer's IP
 * address and the area around their family's home. A halfway result needs none of that: it needs the boroughs, the
 * river and the big roads, so a parent can see where the two areas and the venue sit relative to each other. So the map
 * is drawn on the device from data shipped with the app: no request, no key, no cost at any number of users.
 *
 * SOURCE: Natural Earth 1:10m cultural and physical vectors (https://www.naturalearthdata.com), which are in the public
 * domain. Borough and county outlines from admin_1_states_provinces, the Thames from rivers_lake_centerlines, motorways and
 * main roads from roads. Clipped to the region around London and simplified to about 100 m, which is far below what the
 * map shows and far above what anyone could mistake for a street map.
 *
 * usage: node scripts/build-london-basemap.mjs <dir holding the three Natural Earth .geojson files>
 *   (the files are https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/<name>.geojson)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node scripts/build-london-basemap.mjs <natural-earth-geojson-dir>');
const load = (name) => JSON.parse(readFileSync(join(dir, `${name}.geojson`), 'utf8'));

// The region a halfway between two London-area families can plausibly cover, with margin.
const BBOX = { west: -0.95, south: 51.1, east: 0.75, north: 51.9 };
const TOLERANCE = 0.0009; // degrees, about 100 m of latitude
const inBox = ([x, y]) => x >= BBOX.west && x <= BBOX.east && y >= BBOX.south && y <= BBOX.north;

/** Douglas-Peucker, on lon/lat scaled so a degree of longitude is as long as one of latitude at London. */
const K = Math.cos((51.5 * Math.PI) / 180);
function simplify(points, tolerance = TOLERANCE) {
  if (points.length <= 2) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = [points[a][0] * K, points[a][1]];
    const [bx, by] = [points[b][0] * K, points[b][1]];
    const dx = bx - ax;
    const dy = by - ay;
    const len = Math.hypot(dx, dy);
    let worst = -1;
    let at = -1;
    for (let i = a + 1; i < b; i += 1) {
      const px = points[i][0] * K;
      const py = points[i][1];
      // A closed ring starts and ends on the same point: measure from that point rather than from a zero-length line.
      const d = len < 1e-12 ? Math.hypot(px - ax, py - ay) : Math.abs(dy * px - dx * py + bx * ay - by * ax) / len;
      if (d > worst) { worst = d; at = i; }
    }
    if (worst > tolerance) {
      keep[at] = 1;
      stack.push([a, at], [at, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const round = (p) => [Number(p[0].toFixed(4)), Number(p[1].toFixed(4))];
const linesOf = (geometry) => {
  if (!geometry) return [];
  switch (geometry.type) {
    case 'LineString': return [geometry.coordinates];
    case 'MultiLineString': return geometry.coordinates;
    case 'Polygon': return geometry.coordinates;
    case 'MultiPolygon': return geometry.coordinates.flat();
    default: return [];
  }
};
const keepLine = (line) => line.some(inBox);
const flat = (line) => simplify(line).map(round).flat();

const areas = load('ne_10m_admin_1_states_provinces').features
  .filter((f) => f.properties?.iso_a2 === 'GB' && linesOf(f.geometry).some(keepLine))
  .map((f) => ({ name: f.properties.name, rings: linesOf(f.geometry).filter(keepLine).map(flat).filter((r) => r.length >= 6) }));

const river = load('ne_10m_rivers_lake_centerlines').features
  .filter((f) => f.properties?.name === 'Thames')
  .flatMap((f) => linesOf(f.geometry).filter(keepLine).map(flat));

const roads = load('ne_10m_roads').features
  .filter((f) => ['Major Highway', 'Secondary Highway'].includes(f.properties?.type) && linesOf(f.geometry).some(keepLine))
  .map((f) => ({ ref: f.properties.local || f.properties.label2 || null, motorway: /^M\d/.test(f.properties.local ?? ''), lines: linesOf(f.geometry).filter(keepLine).map(flat) }));

const body = `/**
 * GENERATED by scripts/build-london-basemap.mjs from Natural Earth 1:10m vectors (public domain,
 * https://www.naturalearthdata.com). Do not edit by hand: re-run the script.
 *
 * Coordinates are flat [lon, lat, lon, lat, ...] arrays, simplified to about 100 m.
 */
export interface BasemapArea { name: string; rings: number[][] }
export interface BasemapRoad { ref: string | null; motorway: boolean; lines: number[][] }

export const BASEMAP_BBOX = ${JSON.stringify(BBOX)} as const;
export const BASEMAP_AREAS: BasemapArea[] = ${JSON.stringify(areas)};
export const BASEMAP_RIVER: number[][] = ${JSON.stringify(river)};
export const BASEMAP_ROADS: BasemapRoad[] = ${JSON.stringify(roads)};
export const BASEMAP_SOURCE = 'Natural Earth (public domain)';
`;
const out = join(process.cwd(), 'src', 'data', 'london-basemap.ts');
writeFileSync(out, body);
console.log(`wrote ${out}: ${areas.length} areas, ${river.length} river lines, ${roads.length} roads, ${(Buffer.byteLength(body) / 1024).toFixed(0)} KB`);
